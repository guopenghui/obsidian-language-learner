// 自定义插件来处理相对路径的 .vue 文件导入
function resolveVueImports() {
    return {
        name: 'resolve-vue-imports',
        resolveId(source: string, importer: string) {
            if (source.endsWith('.vue') && !source.startsWith('.') && !source.startsWith('/')) {
                const importerDir = dirname(importer);
                const resolved = resolve(importerDir, source);
                return resolved;
            }
            return null;
        }
    };
}

// 自定义插件来移除 fs 和 path 等 Node.js 内置模块的引用
function removeNodeJsModules() {
    const emptyModuleCode = `
        // Empty module stub for Node.js built-in modules
        // These modules are not available in browser/Obsidian environment
        const emptyStub = {};
        emptyStub.readFileSync = () => new Uint8Array();
        emptyStub.readSync = () => 0;
        emptyStub.existsSync = () => false;
        export default emptyStub;
    `;

    return {
        name: 'remove-nodejs-modules',
        resolveId(source: string) {
            // 将 fs, path, crypto 等模块解析为虚拟 ID
            const nodeModules = ['fs', 'path', 'crypto', 'os', 'util', 'stream', 'buffer'];
            if (nodeModules.includes(source)) {
                return { id: source, external: false };
            }
            return null;
        },
        load(id: string) {
            // 为这些模块返回空内容
            const nodeModules = ['fs', 'path', 'crypto', 'os', 'util', 'stream', 'buffer'];
            if (nodeModules.includes(id)) {
                return emptyModuleCode;
            }
            return null;
        },
        transform(code: string, id: string) {
            // 在转换阶段，处理源代码中的 require 调用
            if (id.includes('node_modules')) {
                let modifiedCode = code;

                // 替换 require('fs'), require('path'), require('crypto')
                modifiedCode = modifiedCode.replace(
                    /require\(["']fs["']\)/g,
                    '({ readFileSync: () => new Uint8Array(), readSync: () => 0, existsSync: () => false })'
                );
                modifiedCode = modifiedCode.replace(
                    /require\(["']path["']\)/g,
                    '({ basename: (s) => s, dirname: (s) => s, join: (...args) => args.join("/") })'
                );
                modifiedCode = modifiedCode.replace(
                    /require\(["']crypto["']\)/g,
                    '({})'
                );

                if (modifiedCode !== code) {
                    return { code: modifiedCode, map: null };
                }
            }
            return null;
        }
    };
}

